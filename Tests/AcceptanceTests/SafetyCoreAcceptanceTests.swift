private final class ReplayEventCapture: @unchecked Sendable {
    private let lock = NSLock()
    private var storage: [PipelineEvent] = []
    func append(_ event: PipelineEvent) { lock.withLock { storage.append(event) } }
    var values: [PipelineEvent] { lock.withLock { storage } }
}

@Test("A12 offline replay crosses the real gate resolver and validator without model egress")
func a12OfflineReplay() async throws {
    let manager = FileManager.default
    let root = manager.temporaryDirectory.appendingPathComponent(UUID().uuidString)
    defer { try? manager.removeItem(at: root) }
    let project = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()
        .deletingLastPathComponent()
        .deletingLastPathComponent()
    let generated = try await ProcessRunner().run(
        project.appendingPathComponent("scripts/make-demo-repo.sh"),
        arguments: [root.path],
        timeout: .seconds(30)
    )
    #expect(generated.status == 0)

    let fixture = try FixtureExecutor().load(
        directory: project.appendingPathComponent("Fixtures/shallow"),
        repositoryRoot: root
    )
    let gate = try #require(ErrorGate().match(fixture.errorText))
    let resolution = try #require(RepositoryResolver().resolve(
        paths: gate.extractedPaths,
        allowlistedRoots: [root]
    ))
    var machine = CandidateStateMachine(dailyCap: DailyCap(limit: 30))
    guard case .admitted = machine.admit(
        hash: ClipboardCandidateFilter.hashPrefix(fixture.errorText),
        at: .distantPast
    ) else {
        Issue.record("fixture was not admitted")
        return
    }

    let events = ReplayEventCapture()
    let outcome = await SpeculationPipeline(
        executor: FixtureReplayExecutor(bundle: fixture, speed: 100)
    ).run(prompt: "fixture replay", repositoryRoot: resolution.root) {
        events.append($0)
    }
    guard case let .fixReady(diff, calls) = outcome else {
        Issue.record("fixture did not validate")
        return
    }

    #expect(calls == 1)
    #expect(diff.text == fixture.finalDiff)
    #expect(events.values.contains(.validating))
    #expect(events.values.contains(.validated))
    let status = try await ProcessRunner().run(
        URL(fileURLWithPath: "/usr/bin/git"),
        arguments: ["status", "--porcelain"],
        currentDirectory: root
    )
    #expect(status.stdout.isEmpty)
}

@Test("A8 post-presentation tracked or untracked dirt blocks Apply without mutation")
func a8DirtyTreeRevalidation() async throws {
    let manager = FileManager.default
    let root = manager.temporaryDirectory.appendingPathComponent(UUID().uuidString)
    try manager.createDirectory(at: root, withIntermediateDirectories: true)
    defer { try? manager.removeItem(at: root) }
    try Data("old\n".utf8).write(to: root.appendingPathComponent("file.txt"))
    try Data("base\n".utf8).write(to: root.appendingPathComponent("other.txt"))
    _ = try await ProcessRunner().run(URL(fileURLWithPath: "/usr/bin/git"), arguments: ["init", "-q"], currentDirectory: root)
    _ = try await ProcessRunner().run(URL(fileURLWithPath: "/usr/bin/git"), arguments: ["add", "file.txt", "other.txt"], currentDirectory: root)
    _ = try await ProcessRunner().run(
        URL(fileURLWithPath: "/usr/bin/git"),
        arguments: ["-c", "user.name=Test", "-c", "user.email=test@example.com", "-c", "commit.gpgsign=false", "commit", "-qm", "base"],
        currentDirectory: root
    )
    let diff = try UnifiedDiffParser().parse(acceptancePatch)
    try await GitApplyChecker().check(diff, repositoryRoot: root)

    let marker = root.appendingPathComponent("untracked.txt")
    try Data("marker\n".utf8).write(to: marker)
    await #expect(throws: PatchApplyError.dirtyTree) {
        try await PatchApplier().apply(diff, repositoryRoot: root)
    }
    #expect(try String(contentsOf: root.appendingPathComponent("file.txt"), encoding: .utf8) == "old\n")

    try manager.removeItem(at: marker)
    try Data("changed\n".utf8).write(to: root.appendingPathComponent("other.txt"))
    await #expect(throws: PatchApplyError.dirtyTree) {
        try await PatchApplier().apply(diff, repositoryRoot: root)
    }
    #expect(try String(contentsOf: root.appendingPathComponent("file.txt"), encoding: .utf8) == "old\n")
}

@Test("A13 held fix excludes candidates and Dismiss permits admission after dedup expiry")
func a13HeldFixExclusionAndReadmission() throws {
    let firstText = "Traceback (most recent call last):\n  File \"/tmp/first.py\", line 1, in <module>\nValueError: first"
    let secondText = "Traceback (most recent call last):\n  File \"/tmp/second.py\", line 2, in <module>\nValueError: second"
    let firstItem = AcceptancePasteboardItem(value: firstText)
    let secondItem = AcceptancePasteboardItem(value: secondText)
    let start = Date(timeIntervalSinceReferenceDate: 3_000)
    var filter = ClipboardCandidateFilter()
    var machine = CandidateStateMachine(dailyCap: DailyCap(limit: 30))

    guard case let .candidate(_, firstHash) = filter.evaluate(firstItem, now: start) else {
        Issue.record("first candidate was not observed")
        return
    }
    #expect(machine.admit(hash: firstHash, at: start) == .admitted(count: 1))
    machine.hold(diff: try UnifiedDiffParser().parse(acceptancePatch))

    guard case let .candidate(_, secondHash) = filter.evaluate(secondItem, now: start.addingTimeInterval(1)) else {
        Issue.record("second candidate was not observed")
        return
    }
    #expect(machine.admit(hash: secondHash, at: start.addingTimeInterval(1)) == .singleflightDrop)

    machine.release()
    #expect(filter.evaluate(secondItem, now: start.addingTimeInterval(2)) == .duplicateDrop(hashPrefix: secondHash))
    guard case let .candidate(_, readmittedHash) = filter.evaluate(
        secondItem,
        now: start.addingTimeInterval(ClipboardCandidateFilter.deduplicationInterval + 2)
    ) else {
        Issue.record("candidate was not readmitted after dedup expiry")
        return
    }
    #expect(readmittedHash == secondHash)
    #expect(machine.admit(hash: readmittedHash, at: start.addingTimeInterval(ClipboardCandidateFilter.deduplicationInterval + 2)) == .admitted(count: 2))
}
